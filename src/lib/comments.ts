/** 厩舎の「木村哲也 (美浦)」→「木村哲也」、馬主の「(有)サンデーレーシング」→「サンデーレーシング」 */
export function commentKey(name: string) {
  return name.replace(/\s*[(（](美浦|栗東|地方|海外|[^)）]{1,3})[)）]\s*$/, "").replace(/[(（](有|株|合|同|一社|社)[)）]/g, "").trim();
}

export function writtenComment(field: GroupField, name: string): Written | null {
  return WRITTEN[field][commentKey(name)] ?? null;
}

export type CommentStats = {
  horses: number; starters: number; winners: number; points: number;
  topName: string | null; avgRate: number | null; // 全体の勝ち上がり率（%）
  prevStarters: number; prevWinners: number;
  sale?: { sold: number; price: number; returnRate: number | null } | null;
};

/** データから組み立てる「ひとこと」。手書きのコメントがない名前にも、同じ口調で */
export function dataComment(field: GroupField, label: string, s: CommentStats): string {
  const parts: string[] = [];
  const rate = s.starters > 0 ? (s.winners / s.starters) * 100 : null;
  if (s.horses === 0) return "";
  if (s.starters === 0) {
    parts.push(`今年の2歳は${s.horses}頭が登録されていますが、まだ中央でデビューした馬はいません。デビュー前から目をつけておくと、後で自慢できるかもしれません。`);
  } else if (rate !== null && s.avgRate !== null && s.starters >= 5) {
    const diff = rate - s.avgRate;
    if (diff >= 8) parts.push(`今年はデビューした${s.starters}頭のうち${s.winners}頭が勝ち上がり。率${rate.toFixed(0)}%は全体（${s.avgRate.toFixed(0)}%）をはっきり上回っていて、今いちばん「乗っている」${label}のひとつです。`);
    else if (diff >= 0) parts.push(`デビュー${s.starters}頭で勝ち上がり${s.winners}頭、率${rate.toFixed(0)}%。全体（${s.avgRate.toFixed(0)}%）並み以上で、手堅く結果を出しています。`);
    else if (diff >= -8) parts.push(`デビュー${s.starters}頭で勝ち上がり${s.winners}頭（${rate.toFixed(0)}%）。数字はまだ平均にわずかに届きませんが、これから使われる馬も多く巻き返しは十分ありそうです。`);
    else parts.push(`デビュー${s.starters}頭で勝ち上がりは${s.winners}頭（${rate.toFixed(0)}%）と、今年はやや苦戦気味。そのぶん人気が落ちている今が、逆に狙い目かもしれません。`);
  } else {
    parts.push(`デビューした${s.starters}頭のうち${s.winners}頭が勝ち上がっています。まだ数が少ないので、これからの数字に注目です。`);
  }
  if (s.topName && s.points > 0) parts.push(`いま稼ぎ頭は${s.topName}。`);
  if (s.prevStarters >= 5) {
    const pr = (s.prevWinners / s.prevStarters) * 100;
    parts.push(`前の世代は出走${s.prevStarters}頭で${s.prevWinners}頭が勝ち上がり（${pr.toFixed(0)}%）でした。`);
  }
  if (s.sale && s.sale.sold >= 3 && s.sale.returnRate !== null) {
    const r = s.sale.returnRate;
    parts.push(r >= 100
      ? `セリで買われた${s.sale.sold}頭は、すでに落札額以上の本賞金を稼いでいます（回収率${r.toFixed(0)}%）。`
      : `セリで買われた${s.sale.sold}頭の回収率は今のところ${r.toFixed(0)}%。ここからどこまで取り返せるか。`);
  }
  return parts.join("");
}
